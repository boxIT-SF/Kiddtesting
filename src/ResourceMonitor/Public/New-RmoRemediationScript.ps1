function New-RmoRemediationScript {
    <#
        .SYNOPSIS
            Writes a PowerShell script that carries the plan and can apply the parts of it that
            are safe to automate.

        .DESCRIPTION
            The generated script does nothing when it is run. It has to be told which actions to
            apply, by id:

                .\tune-PC01.ps1              # print the plan and the ids
                .\tune-PC01.ps1 -List        # ids only
                .\tune-PC01.ps1 -Run av-overlap,startup-Spotify -WhatIf
                .\tune-PC01.ps1 -Run power-plan-saver

            That is deliberate. Most of what makes a machine usable again is a judgement -
            whether this person needs that application resident, whether that agent is the one
            the organisation manages - and a script cannot make those. What it can do is carry
            the reasoning to the machine, and apply the mechanical steps without them being
            retyped.

            Actions with no command, and actions the analysis marked as needing care, are carried
            as documentation only and refuse to run. Nothing that restarts the machine or removes
            software is ever automated.

        .PARAMETER Result
            A result from Invoke-ResourceAnalysis.

        .PARAMETER Path
            Where to write the script.

        .PARAMETER PassThru
            Return the path that was written.

        .EXAMPLE
            New-RmoRemediationScript -Result $result -Path .\tune-PC01.ps1
    #>
    [CmdletBinding()]
    [OutputType([string])]
    param(
        [Parameter(Mandatory, ValueFromPipeline)] [psobject] $Result,
        [Parameter(Mandatory, Position = 0)] [string] $Path,
        [switch] $PassThru
    )

    process {
        function Quote {
            param([AllowNull()] [string] $Text)
            if ($null -eq $Text) { return "''" }
            "'" + ($Text -replace "'", "''") + "'"
        }

        $lines = [System.Collections.Generic.List[string]]::new()
        $stamp = (Get-Date).ToString('yyyy-MM-dd HH:mm:ss')

        $lines.Add('<#')
        $lines.Add("    Tuning plan for $($Result.System.ComputerName)")
        $lines.Add("    Generated by ResourceMonitor $($script:RmoModuleVersion) on $stamp from a $($Result.ScanMode.ToLowerInvariant()) scan.")
        $lines.Add('')
        $lines.Add("    Constraint: $($Result.Plan.Bottleneck)")
        $lines.Add("    Recoverable: $($Result.Plan.RecoverableMemoryText) of memory, $($Result.Plan.RecoverableCpuPercent)% of the processor")
        $lines.Add('')
        $lines.Add('    This script does nothing unless it is given -Run with the ids of the actions to')
        $lines.Add('    apply. Run it with no arguments to read the plan.')
        $lines.Add('#>')
        $lines.Add('[CmdletBinding(SupportsShouldProcess, ConfirmImpact = ''High'')]')
        $lines.Add('param(')
        $lines.Add('    [string[]] $Run,')
        $lines.Add('    [switch] $List')
        $lines.Add(')')
        $lines.Add('')
        $lines.Add('$ErrorActionPreference = ''Stop''')
        $lines.Add('')
        $lines.Add('$plan = @(')

        foreach ($action in $Result.Plan.Actions) {
            # Only mechanical, reversible, single-command steps are ever runnable. Anything that
            # restarts the machine, removes software, or ends a process stays documentation.
            #
            # A command on a process action is a worked example from the catalogue - an exclusion
            # path, a cache location - written for a person to adapt, not a step to apply blind.
            # Only the machine-level findings carry a command that means exactly what it says.
            $automatable = [bool] $action.Command -and $action.Source -eq 'System'
            if ($action.Safety -eq 'Caution') { $automatable = $false }
            if ($action.Effort -in 'Hardware', 'Planned') { $automatable = $false }
            if ($action.Command -match '(?i)Restart-Computer|Remove-AppxPackage|Stop-Process|Remove-Item|Uninstall') {
                $automatable = $false
            }

            $lines.Add('    [pscustomobject]@{')
            $lines.Add("        Id             = $(Quote $action.Id)")
            $lines.Add("        Title          = $(Quote $action.Title)")
            $lines.Add("        Impact         = $(Quote $action.Impact)")
            $lines.Add("        Category       = $(Quote $action.Category)")
            $lines.Add("        Vendor         = $(Quote $action.Vendor)")
            $lines.Add("        Effort         = $(Quote $action.Effort)")
            $lines.Add("        Risk           = $(Quote $action.Safety)")
            $lines.Add("        Evidence       = $(Quote $action.Evidence)")
            $lines.Add("        Detail         = $(Quote $action.Detail)")
            $lines.Add("        Recommendation = $(Quote $action.Recommendation)")
            $lines.Add("        Gain           = $(Quote $action.Gain)")
            $lines.Add("        Automatable    = `$$($automatable.ToString().ToLowerInvariant())")
            if ($automatable) {
                $lines.Add("        Command        = { $($action.Command) }")
            } else {
                $lines.Add("        Command        = `$null")
                $lines.Add("        CommandText    = $(Quote $action.Command)")
            }
            $lines.Add('    }')
        }

        $lines.Add(')')
        $lines.Add('')
        $lines.Add(@'
function Write-Wrapped {
    param([string] $Label, [string] $Text, [int] $Width = 96)
    if (-not $Text) { return }
    $indent = ' ' * 6
    $available = [math]::Max(20, $Width - $indent.Length)
    $words = @($Label) + @($Text -split '\s+' | Where-Object { $_ })
    $current = ''
    foreach ($word in $words) {
        if (-not $current) { $current = $word }
        elseif (($current.Length + 1 + $word.Length) -le $available) { $current = "$current $word" }
        else { Write-Host ($indent + $current); $current = $word }
    }
    if ($current) { Write-Host ($indent + $current) }
}

if ($List) {
    foreach ($action in $plan) {
        $marker = if ($action.Automatable) { '[can run]' } else { '[manual] ' }
        Write-Host ("{0} {1,-8} {2,-34} {3}" -f $marker, $action.Impact, $action.Id, $action.Title)
    }
    return
}

if (-not $Run) {
    Write-Host ''
    Write-Host "Tuning plan - $($plan.Count) actions. Nothing has been changed." -ForegroundColor Cyan
    Write-Host 'Apply one with:  .\<this script> -Run <id>       List ids with:  -List' -ForegroundColor DarkGray
    $number = 1
    foreach ($action in $plan) {
        $colour = switch ($action.Impact) {
            'High'   { 'Red' }
            'Medium' { 'Yellow' }
            default  { 'Gray' }
        }
        Write-Host ''
        Write-Host ("[{0}] {1}. {2}" -f $action.Impact.ToUpperInvariant(), $number, $action.Title) -ForegroundColor $colour
        Write-Host ("      id: {0} | {1} | effort: {2} | risk: {3}" -f
            $action.Id, $action.Category, $action.Effort, $action.Risk) -ForegroundColor DarkGray
        Write-Wrapped 'Measured:' $action.Evidence
        Write-Wrapped 'What it is:' $action.Detail
        Write-Wrapped 'Do this:' $action.Recommendation
        Write-Wrapped 'Expected:' $action.Gain
        if (-not $action.Automatable -and $action.PSObject.Properties['CommandText'] -and $action.CommandText) {
            Write-Host "      Suggested command (not run by this script): $($action.CommandText)" -ForegroundColor DarkGray
        }
        $number++
    }
    Write-Host ''
    return
}

$exitCode = 0
foreach ($id in $Run) {
    $action = $plan | Where-Object { $_.Id -eq $id }
    if (-not $action) {
        Write-Warning "No action with id '$id'. Use -List to see the ids."
        $exitCode = 2
        continue
    }
    if (-not $action.Automatable) {
        Write-Warning "'$id' is not something this script will do for you: $($action.Recommendation)"
        $exitCode = 2
        continue
    }
    if (-not $PSCmdlet.ShouldProcess($action.Title, 'Apply')) { continue }
    try {
        & $action.Command
        Write-Host "Applied: $($action.Title)" -ForegroundColor Green
    } catch {
        Write-Warning "Failed to apply '$id': $($_.Exception.Message)"
        $exitCode = 1
    }
}
exit $exitCode
'@)

        $directory = Split-Path -Path $Path -Parent
        if ($directory -and -not (Test-Path -LiteralPath $directory)) {
            $null = New-Item -ItemType Directory -Path $directory -Force
        }
        ($lines -join [Environment]::NewLine) | Set-Content -LiteralPath $Path -Encoding UTF8

        Write-Verbose "Wrote tuning script to $Path"
        if ($PassThru) { $Path }
    }
}
